// Writes public/_redirects (Netlify / Cloudflare Pages format, real 301s) from src/data/redirects.js.
// Astro itself also emits redirect pages for the same list (see astro.config.mjs), which cover hosts without a _redirects file.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const { build } = require(path.resolve(process.cwd(), 'src/data/redirects.js'));
const list = build();
const body = ['# Generated by scripts/gen-redirects.mjs from src/data/redirects.js - do not edit by hand.', '# Old site URLs -> new site URLs (301).', ...list.map((r) => `${r.from} ${r.to} ${r.status}`), ''].join('\n');
fs.writeFileSync(path.resolve(process.cwd(), 'public/_redirects'), body);
console.log(`public/_redirects: ${list.length} rules`);
